"""Unit tests for tools/sync_requirements_inventory.py.

Hermetic: temporary directories and fixtures only. Does not mutate monorepo inventory.
"""

from __future__ import annotations

import importlib.util
import sys
import tempfile
import unittest
from pathlib import Path


TOOLS_DIR = Path(__file__).resolve().parents[1]
SYNC_PATH = TOOLS_DIR / "sync_requirements_inventory.py"


def load_sync():
    """Load sync_requirements_inventory as a module without executing main()."""
    spec = importlib.util.spec_from_file_location(
        "sync_requirements_inventory", SYNC_PATH
    )
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    sys.modules["sync_requirements_inventory"] = mod
    spec.loader.exec_module(mod)
    return mod


class ExtractPestTitlesTests(unittest.TestCase):
    def setUp(self) -> None:
        self.sync = load_sync()

    def test_double_quoted_it_titles(self):
        text = '''
it("happy: stage json_schema_validate fails [PIPE-002]", function () {
    expect(true)->toBeTrue();
});
'''
        titles = self.sync.extract_pest_titles(text)
        self.assertIn(
            "happy: stage json_schema_validate fails [PIPE-002]", titles
        )

    def test_single_quoted_it_titles(self):
        text = """
it('discovers attribute capabilities from configured path into registry', function () {
    expect(true)->toBeTrue();
});
"""
        titles = self.sync.extract_pest_titles(text)
        self.assertIn(
            "discovers attribute capabilities from configured path into registry",
            titles,
        )

    def test_matrix_it_title_variable_from_foreach_string_array(self):
        text = '''
foreach (['agent', 'mcp'] as $caller) {
    it("edge: rate limit applies to caller {$caller} [D-013]", function () use ($caller) {
        expect(true)->toBeTrue();
    });
}
'''
        titles = self.sync.extract_pest_titles(text)
        self.assertIn("edge: rate limit applies to caller agent [D-013]", titles)
        self.assertIn("edge: rate limit applies to caller mcp [D-013]", titles)

    def test_matrix_title_assigned_then_it_variable(self):
        text = '''
$callers = ['agent', 'job'];
foreach ($callers as $caller) {
    $title = "happy: idempotency first for {$caller} [D-005]";
    it($title, function () use ($caller) {
        expect(true)->toBeTrue();
    });
}
'''
        titles = self.sync.extract_pest_titles(text)
        self.assertIn("happy: idempotency first for agent [D-005]", titles)
        self.assertIn("happy: idempotency first for job [D-005]", titles)

    def test_match_arm_static_titles(self):
        text = '''
foreach (['first', 'replay'] as $scenario) {
    $title = match ($scenario) {
        'first' => "happy: idempotency first for agent [D-005]",
        'replay' => "happy: idempotency replay for agent [D-005]",
    };
    it($title, function () use ($scenario) {});
}
'''
        titles = self.sync.extract_pest_titles(text)
        self.assertIn("happy: idempotency first for agent [D-005]", titles)
        self.assertIn("happy: idempotency replay for agent [D-005]", titles)


