"""Unit tests for tools/generate_requirement_stubs.py no-wipe regeneration.

Hermetic: uses temporary directories only. Does not touch package test suites.
"""

from __future__ import annotations

import importlib.util
import io
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch


TOOLS_DIR = Path(__file__).resolve().parents[1]
GENERATOR_PATH = TOOLS_DIR / "generate_requirement_stubs.py"


def load_generator():
    """Load generate_requirement_stubs as a module without executing main()."""
    spec = importlib.util.spec_from_file_location(
        "generate_requirement_stubs", GENERATOR_PATH
    )
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    # Register so dataclasses / annotations resolve if needed
    sys.modules["generate_requirement_stubs"] = mod
    spec.loader.exec_module(mod)
    return mod


gen = load_generator()


class IsAutoGeneratedStubTests(unittest.TestCase):
    def test_detects_php_auto_generated_marker(self):
        text = gen.php_file_content(
            gen.F("core", "Example/FooTest.php")
        )
        self.assertTrue(gen.is_auto_generated_stub(text))

    def test_detects_go_auto_generated_marker(self):
        spec = gen.F("cli", "internal/foo_todo_test.go", language="go", go_package="foo")
        text = gen.go_file_content(spec)
        self.assertTrue(gen.is_auto_generated_stub(text))

    def test_implemented_php_without_marker_is_not_stub(self):
        text = '<?php\n\ndeclare(strict_types=1);\n\nit("real", function () {\n    expect(true)->toBeTrue();\n});\n'
        self.assertFalse(gen.is_auto_generated_stub(text))

    def test_implemented_go_without_marker_is_not_stub(self):
        text = 'package foo\n\nimport "testing"\n\nfunc TestReal(t *testing.T) {\n\tt.Log("ok")\n}\n'
        self.assertFalse(gen.is_auto_generated_stub(text))


class ShouldWriteStubTests(unittest.TestCase):
    def test_missing_file_should_write(self):
        with tempfile.TemporaryDirectory() as td:
            path = Path(td) / "MissingTest.php"
            self.assertTrue(gen.should_write_stub(path))

    def test_auto_generated_file_should_write(self):
        with tempfile.TemporaryDirectory() as td:
            path = Path(td) / "StubTest.php"
            path.write_text(
                "// AUTO-GENERATED by tools/generate_requirement_stubs.py — do not edit by hand.\n"
                "<?php\n",
                encoding="utf-8",
            )
            self.assertTrue(gen.should_write_stub(path))

    def test_implemented_file_should_not_write(self):
        with tempfile.TemporaryDirectory() as td:
            path = Path(td) / "ImplementedTest.php"
            path.write_text(
                "<?php\n// real implementation\nit('works', fn () => expect(1)->toBe(1));\n",
                encoding="utf-8",
            )
            self.assertFalse(gen.should_write_stub(path))


class WriteFilesNoWipeTests(unittest.TestCase):
    """Hermetic tree: implemented fixtures preserved; pure stubs rewritten."""

    def _layout(self, root: Path) -> None:
        (root / "packages/laravel-capabilities/tests/Unit/Registry").mkdir(parents=True)
        (root / "packages/laravel-capabilities-messaging/tests/Unit").mkdir(parents=True)
        (root / "packages/capabilities-cli/internal").mkdir(parents=True)
        (root / "docs").mkdir(parents=True)

    def test_preserves_implemented_php_and_rewrites_stub(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            self._layout(root)

            impl_path = (
                root
                / "packages/laravel-capabilities/tests/Unit/Registry/InvokePipelineTest.php"
            )
            stub_path = (
                root
                / "packages/laravel-capabilities/tests/Unit/Registry/EmptyStubTest.php"
            )
            implemented_body = (
                "<?php\n\ndeclare(strict_types=1);\n\n"
                "// IMPLEMENTED — must survive regenerate\n"
                'it("real pipeline test", function () {\n'
                "    expect(true)->toBeTrue();\n"
                "});\n"
            )
            stub_body = (
                "<?php\n\n"
                "// AUTO-GENERATED by tools/generate_requirement_stubs.py — do not edit by hand.\n"
                "// Spec-derived unit test stubs. Unit-only, no database — see AGENTS.md.\n"
                "// Package file: Registry/EmptyStubTest.php\n\n"
                "declare(strict_types=1);\n\n"
                'it("old stub case", function () {\n'
                "    // TODO: implement unit test with mocks/fakes (no DB).\n"
                "})->todo();\n\n"
            )
            impl_path.write_text(implemented_body, encoding="utf-8")
            stub_path.write_text(stub_body, encoding="utf-8")

            impl_spec = gen.F("core", "Registry/InvokePipelineTest.php")
            impl_spec.happy("successful invoke", "PIPE-001")
            stub_spec = gen.F("core", "Registry/EmptyStubTest.php")
            stub_spec.happy("new regenerated case", "PIPE-X")

            stats = gen.write_files([impl_spec, stub_spec], root=root)

            after_impl = impl_path.read_text(encoding="utf-8")
            after_stub = stub_path.read_text(encoding="utf-8")

            self.assertEqual(after_impl, implemented_body)
            self.assertIn("new regenerated case", after_stub)
            self.assertIn("AUTO-GENERATED by tools/generate_requirement_stubs.py", after_stub)
            self.assertNotIn("old stub case", after_stub)

            self.assertEqual(stats["skipped"], 1)
            self.assertEqual(stats["php"], 1)  # only stub written
            self.assertGreaterEqual(stats["written"], 1)
            inv = root / "docs/requirements-inventory.md"
            self.assertTrue(inv.is_file())
            self.assertIn("InvokePipelineTest.php", inv.read_text(encoding="utf-8"))

    def test_does_not_mass_delete_implemented_files_outside_catalog_write(self):
        """Implemented tests not targeted for rewrite must remain on disk."""
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            self._layout(root)

            orphan_impl = (
                root
                / "packages/laravel-capabilities/tests/Unit/Registry/HandWrittenTest.php"
            )
            orphan_body = "<?php\n// hand-written implemented suite\n"
            orphan_impl.write_text(orphan_body, encoding="utf-8")

            # Catalog only has a new missing file — must not wipe HandWrittenTest
            missing = gen.F("core", "Registry/BrandNewTest.php")
            missing.happy("brand new scenario", "X")

            gen.write_files([missing], root=root)

            self.assertTrue(orphan_impl.is_file())
            self.assertEqual(orphan_impl.read_text(encoding="utf-8"), orphan_body)
            new_path = (
                root
                / "packages/laravel-capabilities/tests/Unit/Registry/BrandNewTest.php"
            )
            self.assertTrue(new_path.is_file())
            self.assertTrue(gen.is_auto_generated_stub(new_path.read_text(encoding="utf-8")))

    def test_preserves_implemented_go_and_rewrites_todo_stub(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            self._layout(root)

            impl_go = root / "packages/capabilities-cli/internal/real_test.go"
            stub_go = root / "packages/capabilities-cli/internal/foo_todo_test.go"
            impl_body = (
                'package internal\n\nimport "testing"\n\n'
                "func TestReal(t *testing.T) {\n\tt.Log(\"implemented\")\n}\n"
            )
            stub_body = (
                "package internal\n\n"
                'import "testing"\n\n'
                "// AUTO-GENERATED by tools/generate_requirement_stubs.py — do not edit by hand.\n"
                "func TestOld(t *testing.T) {\n"
                '\tt.Skip("TODO: implement")\n'
                "}\n"
            )
            impl_go.write_text(impl_body, encoding="utf-8")
            stub_go.write_text(stub_body, encoding="utf-8")

            impl_spec = gen.F(
                "cli", "internal/real_test.go", language="go", go_package="internal"
            )
            impl_spec.add("go", "real scenario", "CLI")
            stub_spec = gen.F(
                "cli", "internal/foo_todo_test.go", language="go", go_package="internal"
            )
            stub_spec.add("go", "fresh stub scenario", "CLI")

            stats = gen.write_files([impl_spec, stub_spec], root=root)

            self.assertEqual(impl_go.read_text(encoding="utf-8"), impl_body)
            rewritten = stub_go.read_text(encoding="utf-8")
            self.assertIn("AUTO-GENERATED", rewritten)
            # go_test_func_name capitalizes segments from the catalog title
            self.assertIn("func TestFreshStubScenario", rewritten)
            self.assertEqual(stats["skipped"], 1)
            self.assertEqual(stats["go"], 1)

    def test_main_prints_written_and_skipped_counts(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            self._layout(root)

            impl_path = (
                root
                / "packages/laravel-capabilities/tests/Unit/Registry/InvokePipelineTest.php"
            )
            impl_path.write_text(
                "<?php\n// implemented without marker\n", encoding="utf-8"
            )

            files = [gen.F("core", "Registry/InvokePipelineTest.php")]
            files[0].happy("x", "Y")

            buf = io.StringIO()
            with patch.object(gen, "ROOT", root):
                with patch.object(gen, "build_catalog", return_value=files):
                    with patch("sys.stdout", buf):
                        gen.main()

            out = buf.getvalue()
            # main also prints skip detail to stderr; capture combined via stats line on stdout
            self.assertIn("skipped=1", out.lower())
            self.assertIn("written=", out.lower())


if __name__ == "__main__":
    unittest.main()
